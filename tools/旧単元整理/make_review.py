# -*- coding: utf-8 -*-
"""引きつぎ表を、人が読んでレビューできる形（Markdown）に書き出す。"""
import json, io, os
from collections import Counter, defaultdict

SP = os.path.dirname(os.path.abspath(__file__))
m = json.load(io.open(SP + "/matched.json", encoding="utf-8"))
un = json.load(io.open(SP + "/unmatched.json", encoding="utf-8"))
mp = json.load(io.open(SP + "/mapping.json", encoding="utf-8"))
nid = [n for v in mp.values() for n in v]
multi = {k: v for k, v in Counter(nid).items() if v > 1}
BQ = chr(96)  # バッククォート

o = []
A = o.append
A("# 旧単元の正誤記録 引きつぎ表（レビュー用）2026-09-08")
A("")
A("作成: kosukequiz-battle 担当 claude-4c [8cc457] / レビュー依頼先: claude-18 [282212]")
A("")
A("## 何をしようとしているか")
A("夏期講習の復習編5〜8に置きかわった**旧単元289問を data.js から消す**。")
A("そのとき、端末に残っている正誤の記録を、新しい問題に引きつぐ。")
A("")
A("消す旧単元: 5.近畿地方(57) / 6.中部地方(78) / 7.関東地方(66) / 8.東北地方(56) / 8.北海道地方(32)")
A("")
A("## ★前回（328af80）の失敗を繰り返さないための方針")
A("前回は「答えの語の**包含一致**」で機械的に埋めたため、")
A("`沖縄 → 近郊農業` / `「40」 → 「60」` / `沖合漁業 → 遠洋漁業` のような")
A("**意味的に別物への紐づけが大量に発生**した（完全一致は329件中95件だけ）。")
A("**配信後は一度きり実行なので、いまも直せない。**")
A("")
A("今回は次の3つを守っている。")
A("1. **答えの完全一致のみ。包含一致は使わない**")
A("2. **1対多は採らない**（同じ語で複数当たるものは別物が混ざるため見送り）")
A("3. **対応がつかないものは、無理に紐づけず記録を捨てる**")
A("")
A("### 答えの比べ方（ここが今回の肝）")
A("括弧の中だけでは足りない。実データにこういうものがある。")
A("")
A("```")
A("旧 t5-9    大阪府に広がり，近郊農業がさかんな（⑨大阪）平野です。")
A("新 kaki5_12 （大阪）平野です。   ← これが正しい相手")
A("新 kaki5_13 （大阪）湾です。     ← 括弧の中だけ見ると「大阪」で一致してしまう")
A("```")
A("")
A("さらに、括弧の切れ目が旧と新でずれることがある。")
A("")
A("```")
A("旧 t8t-14  …日本一長い山脈は（奥羽山脈）です。   ← 括弧の中に「山脈」がある")
A("新 kaki8_21 （奥羽）山脈です。                    ← 括弧の外に「山脈」がある")
A("```")
A("")
A("→ **括弧の中と直後の語をつないで1つの語にしてから、完全一致で比べている。**")
A("　（「奥羽」＋「山脈」＝「奥羽山脈」でそろう。「大阪平野」と「大阪湾」は別物のまま）")
A("→ 旧問題の「（地図で位置を確認）」のような注記は、答えではないので落としている。")
A("")
A("## 数字")
A("")
A("| | 件数 |")
A("|---|---|")
A("| 消す旧問題 | **289** |")
A("| **引きつぐ（1対1・完全一致）** | **%d（%d%%）** | " % (len(mp), len(mp) * 100 // 289))
A("| 1対多で見送り | %d |" % sum(1 for r in un if r[2].startswith("【1対多】")))
A("| 対応が見つからず記録を捨てる | %d |" % sum(1 for r in un if not r[2].startswith("【1対多】")))
A("| 引きつぎ先の新id | %d種（延べ%d） |" % (len(set(nid)), len(nid)))
A("| 複数の旧問題が同じ新問題を指すもの | %d件 |" % len(multi))
A("")
A("**前回は87%%を「対応がついた」としていたが、今回は%d%%。**" % (len(mp) * 100 // 289))
A("残りは捨てる。**誤って紐づけるより、記録が消えるほうがまし**という判断（C-7）。")
A("")
A("## ★見ていただきたい点")
A("1. **引きつぎ表に、意味的におかしい対応が混ざっていないか**（下の全件表）")
A("2. **捨てる側に、本当は拾えるものが混ざっていないか**（下の一覧）")
A("3. **複数の旧問題が同じ新問題を指すケース**（下記）。")
A("   `mergeStatEntries` は correct/wrong を**足し合わせる**ので、**正解数が二重に入る**。")
A("   同じ問題が旧単元に2回出ていたケースなので妥当だと考えているが、判断をお願いしたい。")
A("")
rev = defaultdict(list)
for k, v in mp.items():
    for n in v:
        rev[n].append(k)
for n, olds in sorted(rev.items()):
    if len(olds) > 1:
        A("- %s%s%s ← %s" % (BQ, n, BQ, " , ".join(BQ + x + BQ for x in olds)))
A("")
A("## 引きつぎ表（全%d件）" % len(m))
A("")
A("| 旧id | 旧単元 | → 新id | 一致した語 | 旧の答え | 新の答え |")
A("|---|---|---|---|---|---|")
for r in sorted(m, key=lambda x: (x["旧単元"], x["旧id"])):
    oa = r["旧答え"].replace("　", "").replace("|", "｜")[:38]
    na = r["新答え"][0].replace("|", "｜")[:30]
    A("| %s%s%s | %s | %s%s%s | %s | %s | %s |" %
      (BQ, r["旧id"], BQ, r["旧単元"], BQ, r["新id"][0], BQ, r["答え"].replace("|", "｜"), oa, na))
A("")
A("## 引きつがないもの（記録を捨てる・全%d件）" % len(un))
A("")
A("| 旧id | 旧単元 | 答え | 問題文 |")
A("|---|---|---|---|")
for r in sorted(un, key=lambda x: (x[1], x[0])):
    A("| %s%s%s | %s | %s | %s |" %
      (BQ, r[0], BQ, r[1], r[2].replace("|", "｜")[:34], r[3].replace("|", "｜")[:44]))

p = SP + "/引きつぎ表_レビュー用.md"
io.open(p, "w", encoding="utf-8").write("\n".join(o))
print("書きました:", p)
print("行数:", len(o))
